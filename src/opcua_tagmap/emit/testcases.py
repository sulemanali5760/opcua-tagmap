"""Render discovered tags as test-case stubs.

The output is the YAML shape read by opc-ua-test-automation-pipeline: one file
per numeric tag, with the structure filled in and every limit left blank.

The blanks are the point. This module must never guess a limit — a plausible
invented number produces a test that passes for no reason, which is worse than
having no test at all. Limits come from a datasheet and a person.

Pure: takes TagNode objects, returns text. No network, no files.
"""

from ..model import TagNode

# OPC UA variant type names that a min/max spec can actually be applied to.
NUMERIC_TYPES = frozenset({
    "Double", "Float",
    "SByte", "Byte",
    "Int16", "UInt16", "Int32", "UInt32", "Int64", "UInt64",
})

# Industrial tag names usually carry their unit as a suffix. This is a
# convenience only, and the generated file says so.
_UNIT_SUFFIXES = [
    ("_mbar", "mbar"), ("_bar", "bar"), ("_kPa", "kPa"), ("_Pa", "Pa"),
    ("_mV", "mV"), ("_V", "V"), ("_mA", "mA"), ("_A", "A"),
    ("_kW", "kW"), ("_W", "W"), ("_kWh", "kWh"),
    ("_ms", "ms"), ("_s", "s"), ("_Hz", "Hz"),
    ("_rpm", "rpm"), ("_C", "C"), ("_K", "K"),
    ("_pct", "%"), ("_mm", "mm"), ("_m", "m"), ("_l", "l"),
]

_TEMPLATE = """\
# Generated by opcua-tagmap from {endpoint}
#
# This is a STUB. It will not judge anything until you give it a limit:
# uncomment min and/or max under `spec` and put the real number there,
# taken from the datasheet or the machine specification.
#
# If this variable does not need a test, delete this file.

test_id: {test_id}
title: TODO - what is being proven about {display_name}?
author: TODO
hypothesis: >
  TODO - what do you believe is true, and why does it matter?
procedure:
  - TODO - how is the machine driven while this is measured?
  - Sample {display_name} for the duration of that event.

variable: {display_name}
node_id: {node_id}          # {browse_path}

# Only check while something else is happening - e.g. only during an inrush,
# or only while the motor runs. Delete both lines to check the whole run.
# condition_variable: TODO
# condition_min: 0.0

spec:
  # min:{units_min_pad}     # lower limit, if there is one
  # max:{units_min_pad}     # upper limit, if there is one
  units: {units}{units_comment}

expected_result: >
  TODO - state the pass condition in one sentence.
on_failure: >
  TODO - if this fails, what should someone go and look at?
"""


def is_numeric(tag: TagNode) -> bool:
    """True when a min/max spec can be applied to this tag."""
    return tag.datatype in NUMERIC_TYPES


def guess_units(display_name: str) -> tuple[str, bool]:
    """Best-effort unit from a tag-name suffix.

    Returns (units, guessed). `guessed` is False when nothing matched, so the
    caller can mark the field as needing attention rather than silently
    asserting a unit that is not there.
    """
    for suffix, unit in _UNIT_SUFFIXES:
        if display_name.endswith(suffix):
            return unit, True
    return "TODO", False


def stub_filename(tag: TagNode) -> str:
    """File name for a tag's stub, safe on every platform."""
    safe = "".join(c if (c.isalnum() or c in "-_") else "_"
                   for c in tag.display_name)
    return f"TC-{safe}.yaml"


def render(tag: TagNode, endpoint: str) -> str:
    """Build one test-case stub. Limits are left blank deliberately."""
    units, guessed = guess_units(tag.display_name)
    return _TEMPLATE.format(
        endpoint=endpoint,
        test_id=f"TC-{tag.display_name}",
        display_name=tag.display_name,
        node_id=tag.node_id,
        browse_path=tag.browse_path,
        units=units,
        units_comment="" if guessed else "   # could not infer from the name",
        units_min_pad="",
    )


def plan(tags: list[TagNode], endpoint: str) -> tuple[list, list]:
    """Split tags into stubs to write and tags that cannot have one.

    Returns (stubs, skipped) where stubs is a list of (filename, text) and
    skipped is a list of (tag, reason).
    """
    stubs, skipped = [], []
    for tag in tags:
        if is_numeric(tag):
            stubs.append((stub_filename(tag), render(tag, endpoint)))
        else:
            skipped.append(
                (tag, f"{tag.datatype} - a min/max spec cannot express it")
            )
    return stubs, skipped
